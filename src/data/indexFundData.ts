// --- A/C类份额持有成本精确测算函数 ---
export function calculateShareClassCost(
  fund: IndexFundItem,
  amount: number, // 投资金额 (元)
  holdingDays: number // 持有天数
): CostSimulationResult {
  const holdingYears = holdingDays / 365.0;

  // A 类成本计算：
  // 1. 前端申购费 (一次性扣除): amount * discountedSubscriptionFee
  // 2. 期间管理费 + 托管费: amount * (managementFee + custodyFee)% * holdingYears
  // 3. 赎回费: 如果持有 >= 365 天通常为0，7~365天约0.5%，<7天1.5%
  let redemptionRateA = 0;
  if (holdingDays < 7) {
    redemptionRateA = 0.015;
  } else if (holdingDays < 365) {
    redemptionRateA = 0.005;
  } else {
    redemptionRateA = 0.00;
  }

  const feeA_subscription = amount * (fund.discountedSubscriptionFee / 100.0);
  const feeA_management_custody = amount * ((fund.managementFee + fund.custodyFee) / 100.0) * holdingYears;
  const feeA_redemption = amount * redemptionRateA;
  const totalCostA = Math.round((feeA_subscription + feeA_management_custody + feeA_redemption) * 100) / 100;

  // C 类成本计算：
  // 1. 前端申购费: 0
  // 2. 期间管理费 + 托管费 + 销售服务费 (通常0.25%~0.40%): amount * (management + custody + salesService)% * holdingYears
  // 3. 赎回费: <7天 1.5%，>=7天 0
  let redemptionRateC = holdingDays < 7 ? 0.015 : 0.00;
  const cSalesServiceFee = fund.salesServiceFee > 0 ? fund.salesServiceFee : 0.25; // 若未配置默认取0.25%
  const feeC_holding = amount * ((fund.managementFee + fund.custodyFee + cSalesServiceFee) / 100.0) * holdingYears;
  const feeC_redemption = amount * redemptionRateC;
  const totalCostC = Math.round((feeC_holding + feeC_redemption) * 100) / 100;

  // 临界天数计算：当 A类费用 = C类费用时的天数
  // 忽略短期赎回惩罚，长期看:
  // A类总费率 = 申购费率(约0.12%) + (管理+托管)*Y
  // C类总费率 = 0 + (管理+托管 + 销售服务费)*Y
  // 两者相等的年数: Y = 申购费率 / 销售服务费率
  // 临界天数 = (0.12% / 0.25%) * 365 ≈ 175 天 (若赎回费考虑，通常在 180~270 天左右)
  const estimatedCrossoverDays = Math.round((fund.discountedSubscriptionFee / cSalesServiceFee) * 365) + 14;

  const costDifference = Math.abs(Math.round((totalCostA - totalCostC) * 100) / 100);
  const isAClassBetter = totalCostA < totalCostC;
  const recommendedClass = isAClassBetter ? 'A类' : 'C类';

  const explanation = isAClassBetter
    ? `预计持有 ${holdingDays} 天（超过盈亏平衡点约 ${estimatedCrossoverDays} 天）。A类单次买断申购费（折后仅 ${fund.discountedSubscriptionFee}%），无持续销售服务费，长期节省 ¥${costDifference} 元成本。`
    : `预计持有 ${holdingDays} 天（低于盈亏平衡点约 ${estimatedCrossoverDays} 天）。C类免收申购费且满7天免赎回费，虽然多出每年约 ${cSalesServiceFee}% 的销售服务费，但在短期波段中节省 ¥${costDifference} 元。`;

  return {
    fundCode: fund.code,
    fundName: fund.name,
    targetIndex: fund.targetIndex,
    holdingDays,
    investmentAmount: amount,
    classACost: totalCostA,
    classCCost: totalCostC,
    costDifference,
    recommendedClass,
    crossoverDays: estimatedCrossoverDays,
    explanation,
  };
}

